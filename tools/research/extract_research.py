#!/usr/bin/env python3
"""Research dump: turns raw WoW Forever DB2 CSVs into human-readable markdown.

Usage: python3 tools/research/extract_research.py RAW_DIR OUT_DIR

Writes:
  OUT_DIR/talents/<class>.md   every talent node per class tree (spec, tier, column,
                               ranks, prerequisites, flags, spell IDs per rank)
  OUT_DIR/talents-summary.md   per-tree counts + Forever-vs-legacy-Talent-table diff
  OUT_DIR/class-spells.md      class abilities from SkillLineAbility with rank chains

This is a research artifact, not the production data pipeline (that is Phase 1,
see docs/PLAN.md). Output is regenerated; never hand-edit it.
"""
import csv
import collections
import os
import sys

RAW, OUT = sys.argv[1], sys.argv[2]


def load(table):
    path = os.path.join(RAW, table + ".csv")
    with open(path, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


spell_name = {r["ID"]: r["Name_lang"] for r in load("SpellName")}
skill_line = {r["ID"]: r for r in load("SkillLine")}
classes = {}
for r in load("ChrClasses"):
    classes[int(r["ID"])] = r["Name_lang"]

# Tree -> class. The tree's SkillLine is one of the class's spec skill lines.
SPEC_TO_CLASS = {
    "Arms": "Warrior", "Retribution": "Paladin", "Beast Mastery": "Hunter",
    "Combat": "Rogue", "Discipline": "Priest", "Enhancement": "Shaman",
    "Arcane": "Mage", "Demonology": "Warlock", "Balance": "Druid",
}
CLASS_MASK = {"Warrior": 1, "Paladin": 2, "Hunter": 4, "Rogue": 8, "Priest": 16,
              "Shaman": 64, "Mage": 128, "Warlock": 256, "Druid": 1024}

tree_class = {}
for r in load("SkillLineXTraitTree"):
    tree_class[r["TraitTreeID"]] = SPEC_TO_CLASS[skill_line[r["SkillLineID"]]["DisplayName_lang"]]

tabs = load("TalentTab")
spec_names = {c: [t["Name_lang"] for t in sorted(
    (t for t in tabs if int(t["ClassMask"]) == m), key=lambda t: int(t["OrderIndex"]))]
    for c, m in CLASS_MASK.items()}

nodes = {r["ID"]: r for r in load("TraitNode")}
entries = {r["ID"]: r for r in load("TraitNodeEntry")}
defs = {r["ID"]: r for r in load("TraitDefinition")}
node_entries = collections.defaultdict(list)
for r in sorted(load("TraitNodeXTraitNodeEntry"), key=lambda r: int(r["_Index"])):
    node_entries[r["TraitNodeID"]].append(entries[r["TraitNodeEntryID"]])
group_nodes = collections.defaultdict(set)
node_groups = collections.defaultdict(set)
for r in load("TraitNodeGroupXTraitNode"):
    group_nodes[r["TraitNodeGroupID"]].add(r["TraitNodeID"])
    node_groups[r["TraitNodeID"]].add(r["TraitNodeGroupID"])
conds = {r["ID"]: r for r in load("TraitCond")}
group_conds = collections.defaultdict(list)
for r in load("TraitNodeGroupXTraitCond"):
    group_conds[r["TraitNodeGroupID"]].append(conds[r["TraitCondID"]])
prereq = collections.defaultdict(set)
for r in load("TraitEdge"):
    prereq[r["RightTraitNodeID"]].add(r["LeftTraitNodeID"])

# Rank chains: talent rank N spell IDs come from the legacy Talent table when the
# rank-1 spell matches; Forever Trait entries only store rank 1 + MaxRanks.
legacy_ranks = {}
for t in load("Talent"):
    ranks = [t[f"SpellRank_{i}"] for i in range(9) if t[f"SpellRank_{i}"] not in ("0", "")]
    if ranks:
        legacy_ranks[ranks[0]] = ranks


def node_info(n):
    out = []
    for e in node_entries[n["ID"]]:
        d = defs[e["TraitDefinitionID"]]
        sid = d["SpellID"]
        name = d["OverrideName_lang"] or spell_name.get(sid, f"spell {sid}")
        out.append((name, sid, int(e["MaxRanks"])))
    return out


os.makedirs(os.path.join(OUT, "talents"), exist_ok=True)
summary = ["# WoW Forever talent trees — summary", "",
           "Generated by `tools/research/extract_research.py` from wago.tools DB2 exports.", "",
           "| Class | Spec | Talents | Max points | Tiers | New vs legacy Talent table |",
           "|---|---|---|---|---|---|"]
all_legacy_rank1 = set(legacy_ranks)

for tree_id, cls in sorted(tree_class.items(), key=lambda kv: kv[1]):
    tnodes = [n for n in nodes.values() if n["TraitTreeID"] == tree_id]
    tgroups = {g for n in tnodes for g in node_groups[n["ID"]]}
    # Specs are laid out as three side-by-side columns; cluster nodes by X position.
    xs_sorted = sorted(tnodes, key=lambda n: int(n["PosX"]))
    clusters, last_x = [], None
    for n in xs_sorted:
        x = int(n["PosX"])
        if last_x is None or x - last_x > 1500:
            clusters.append([])
        clusters[-1].append(n)
        last_x = x
    all_ys = sorted({int(n["PosY"]) for n in tnodes})
    # tier gating: conditioned groups with SpentAmountRequired, scoped to a spec group
    node_gate = {}
    for g in tgroups:
        for c in group_conds[g]:
            amt = int(c["SpentAmountRequired"])
            if amt:
                for x in group_nodes[g]:
                    node_gate[x] = max(node_gate.get(x, 0), amt)
    lines = [f"# {cls} — Forever talent tree (TraitTree {tree_id})", "",
             "Columns: tier (row, 1-based) / col (0-based, within the spec) / points required in "
             "spec to unlock / max ranks / prerequisites / node flags. `flags=8` nodes look "
             "hidden or disabled in this build — verify in game.", ""]
    for idx, members in enumerate(clusters):
        spec = spec_names[cls][idx] if idx < len(spec_names[cls]) else f"Spec {idx}"
        minx = min(int(n["PosX"]) for n in members)
        members = sorted(members, key=lambda n: (int(n["PosY"]), int(n["PosX"])))
        ys = all_ys
        lines += [f"## {spec}", "", "| Tier | Col | Req | Talent | Ranks | Rank spell IDs | Prereq | Flags |",
                  "|---|---|---|---|---|---|---|---|"]
        pts, new = 0, []
        for n in members:
            tier = ys.index(int(n["PosY"])) + 1
            col = (int(n["PosX"]) - minx) // 600
            info = node_info(n)
            name = " / ".join(i[0] for i in info) or "?"
            maxr = info[0][2] if info else 0
            pts += maxr
            r1 = info[0][1] if info else "0"
            ranks = legacy_ranks.get(r1, [r1])
            if len(ranks) != maxr:
                ranks = ranks + ["(rank count differs from legacy: verify)"]
            if r1 not in all_legacy_rank1:
                new.append(name)
            pre = ", ".join(" / ".join(i[0] for i in node_info(nodes[p])) for p in prereq.get(n["ID"], ()) if p in nodes)
            choice = " (choice node)" if n["Type"] == "1" else ""
            lines.append(f"| {tier} | {col} | {node_gate.get(n['ID'], 0)} | {name}{choice} | {maxr} | "
                         f"{', '.join(ranks)} | {pre} | {n['Flags']} |")
        lines.append("")
        summary.append(f"| {cls} | {spec} | {len(members)} | {pts} | {len({int(n['PosY']) for n in members})} | {', '.join(new) or '—'} |")
    with open(os.path.join(OUT, "talents", cls.lower() + ".md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

# Talent point currency
summary += ["", "## Talent point sources", ""]
cur = {r["ID"]: r for r in load("TraitCurrency")}
src = collections.Counter(r["TraitCurrencyID"] for r in load("TraitCurrencySource"))
for cid, r in cur.items():
    summary.append(f"- Currency {cid}: max {r['SourcedMax']}, {src[cid]} source rows")
with open(os.path.join(OUT, "talents-summary.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(summary) + "\n")

# Class spells
levels = {r["SpellID"]: r for r in load("SpellLevels") if r["DifficultyID"] == "0"}
sla = load("SkillLineAbility")
spec_skill_ids = {r["ID"] for r in skill_line.values() if r["CategoryID"] == "7"}
lines = ["# WoW Forever class spells (SkillLineAbility, class skill lines)", "",
         "Grouped by skill line; ranks are ordered by required level. Generated research dump.", ""]
by_class = collections.defaultdict(lambda: collections.defaultdict(list))
mask_to_class = {v: k for k, v in CLASS_MASK.items()}
for r in sla:
    if r["SkillLine"] not in spec_skill_ids:
        continue
    sl = skill_line[r["SkillLine"]]["DisplayName_lang"]
    cm = int(r["ClassMask"] or 0)
    owners = [c for m, c in mask_to_class.items() if cm & m] or [
        c for c, specs in spec_names.items() if sl in specs] or ["Unknown"]
    for c in owners:
        by_class[c][sl].append(r["Spell"])
for c in sorted(by_class):
    lines.append(f"## {c}")
    for sl in sorted(by_class[c]):
        chains = collections.defaultdict(list)
        for sid in by_class[c][sl]:
            chains[spell_name.get(sid, sid)].append(sid)
        lines.append(f"### {sl}")
        for nm in sorted(chains):
            ids = sorted(chains[nm], key=lambda s: int(levels.get(s, {}).get("BaseLevel", 0) or 0))
            lv = [levels.get(s, {}).get("BaseLevel", "?") for s in ids]
            lines.append(f"- **{nm}** — {len(ids)} rank(s): " +
                         ", ".join(f"{s}@L{l}" for s, l in zip(ids, lv)))
        lines.append("")
with open(os.path.join(OUT, "class-spells.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")
print("done")
